#!/usr/bin/env bun
/**
 * Generates docs/DATA_DICTIONARY.md from the live PostgreSQL schema.
 *
 *   bun run schema:docs
 *
 * The file is generated, never hand-edited: tests/m1/data-dictionary.test.ts renders the
 * same markdown from a real database and fails when the committed file drifts.
 */
import { writeFileSync } from 'node:fs';
import { createDb, type Db } from '../server/db/client';

interface TableRow {
  table_name: string;
  rls: boolean;
}

interface ColumnRow {
  table_name: string;
  column_name: string;
  data_type: string;
  udt_name: string;
  is_nullable: 'YES' | 'NO';
  column_default: string | null;
  character_maximum_length: number | null;
  numeric_precision: number | null;
  numeric_scale: number | null;
}

interface ConstraintRow {
  table_name: string;
  conname: string;
  contype: 'p' | 'u' | 'f' | 'c';
  definition: string;
}

const typeOf = (column: ColumnRow): string => {
  const { data_type, udt_name } = column;
  if (data_type === 'ARRAY') return `${udt_name.replace(/^_/, '')}[]`;
  if (data_type === 'character varying') {
    return `character varying(${column.character_maximum_length ?? '?'})`;
  }
  if (data_type === 'character') return `character(${column.character_maximum_length ?? '?'})`;
  if (data_type === 'numeric' && column.numeric_precision !== null) {
    return `numeric(${column.numeric_precision},${column.numeric_scale ?? 0})`;
  }
  return data_type;
};

const cell = (value: string | null): string =>
  value === null || value === '' ? '—' : `\`${value.replace(/\|/g, '\\|')}\``;

const CONSTRAINT_LABEL: Record<ConstraintRow['contype'], string> = {
  p: 'primary key',
  u: 'unique',
  f: 'foreign key',
  c: 'check',
};

export const renderDictionary = async (db: Db): Promise<string> => {
  const tables = await db.unsafe<TableRow>(
    `select c.relname as table_name, c.relrowsecurity as rls
       from pg_class c join pg_namespace n on n.oid = c.relnamespace
      where n.nspname = 'public' and c.relkind = 'r'
      order by c.relname`,
  );
  const columns = await db.unsafe<ColumnRow>(
    `select table_name, column_name, data_type, udt_name, is_nullable, column_default,
            character_maximum_length, numeric_precision, numeric_scale
       from information_schema.columns
      where table_schema = 'public'
      order by table_name, ordinal_position`,
  );
  const constraints = await db.unsafe<ConstraintRow>(
    `select rel.relname as table_name, con.conname, con.contype,
            pg_get_constraintdef(con.oid) as definition
       from pg_constraint con
       join pg_class rel on rel.oid = con.conrelid
       join pg_namespace n on n.oid = rel.relnamespace
      where n.nspname = 'public' and con.contype in ('p','u','f','c')
      order by rel.relname, con.conname`,
  );

  const tableNames = new Set(tables.map((table) => table.table_name));
  const visibleColumns = columns.filter((column) => tableNames.has(column.table_name));
  const byTable = new Map<string, ColumnRow[]>();
  for (const column of visibleColumns) {
    const bucket = byTable.get(column.table_name) ?? [];
    bucket.push(column);
    byTable.set(column.table_name, bucket);
  }
  const constraintOrder: ConstraintRow['contype'][] = ['p', 'u', 'f', 'c'];
  const constraintsOf = (table: string): ConstraintRow[] =>
    constraints
      .filter((constraint) => constraint.table_name === table)
      .sort(
        (a, b) =>
          constraintOrder.indexOf(a.contype) - constraintOrder.indexOf(b.contype) ||
          a.conname.localeCompare(b.conname),
      );

  const lines: string[] = [
    '# Data dictionary (generated)',
    '',
    'Generated from the live PostgreSQL schema by `bun run schema:docs`.',
    'Do not edit this file by hand: `tests/m1/data-dictionary.test.ts` renders the same',
    'markdown from the database and fails when the two disagree.',
    '',
    `- Tables: ${tables.length}`,
    `- Columns: ${visibleColumns.length}`,
    `- Constraints: ${constraints.length}`,
    '',
  ];

  for (const table of tables) {
    lines.push(`## \`${table.table_name}\``, '');
    lines.push(`RLS: ${table.rls ? 'enabled' : '**not enabled**'}`, '');
    lines.push('| Column | Type | Nullable | Default |');
    lines.push('|---|---|---|---|');
    for (const column of byTable.get(table.table_name) ?? []) {
      lines.push(
        `| \`${column.column_name}\` | ${typeOf(column)} | ${
          column.is_nullable === 'YES' ? 'yes' : 'no'
        } | ${cell(column.column_default)} |`,
      );
    }
    const tableConstraints = constraintsOf(table.table_name);
    if (tableConstraints.length > 0) {
      lines.push('', '**Constraints**', '');
      for (const constraint of tableConstraints) {
        lines.push(
          `- ${CONSTRAINT_LABEL[constraint.contype]} \`${constraint.conname}\`: \`${constraint.definition}\``,
        );
      }
    }
    lines.push('');
  }

  return lines.join('\n');
};

if (import.meta.main) {
  const url = process.env.DATABASE_ADMIN_URL ?? process.env.DATABASE_URL;
  if (!url) {
    console.error('DATABASE_URL (or DATABASE_ADMIN_URL) is required to introspect the schema.');
    process.exit(2);
  }
  const db = (await createDb({ mode: 'postgres', databaseUrl: url })) as Db;
  const markdown = await renderDictionary(db);
  writeFileSync('docs/DATA_DICTIONARY.md', markdown);
  console.log(`wrote docs/DATA_DICTIONARY.md (${markdown.split('\n').length} lines)`);
  await db.close();
}
